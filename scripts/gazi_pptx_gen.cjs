// ─── pptxgenjs ASSEMBLER ─────────────────────────────────────────────────────
async function main(){
  const pptx=new PptxGenJS();
  pptx.layout='LAYOUT_4x3';
  pptx.author='Ankara Bilkent Sehir Hastanesi';
  pptx.title='Atesli Silah Yaralanmalari';
  pptx.subject='Adli Tip Klinigi';

  // Extract cover image from sunum_final.pptx
  const JSZip=require('jszip');
  const srcZip=await JSZip.loadAsync(fs.readFileSync('client/public/sunum_final.pptx'));
  const coverImgBuf=await srcZip.file('ppt/media/image-1-1.png').async('nodebuffer');
  const coverImgPath='/tmp/cover_bg.png';
  fs.writeFileSync(coverImgPath,coverImgBuf);

  // ─── KITAP SAYFA GÖRSELLERİ ────────────────────────────────────────────────
  const path=require('path');
  const KNIGHT_GS_DIR='attached_assets/slide_images/knight_gs';
  const DIMIAO_DIR='attached_assets/slide_images/dimiao';
  const KNIGHT_GS_OFFSET=244;

  function findKnightGsImg(bookPage){
    const pdfPage=bookPage-KNIGHT_GS_OFFSET;
    if(pdfPage<1||pdfPage>35) return null;
    const padded=String(pdfPage).padStart(2,'0');
    const f=path.join(KNIGHT_GS_DIR,`page_${pdfPage}-${padded}.png`);
    return fs.existsSync(f)?f:null;
  }
  function findDiMaioImg(bookPage){
    const candidates=[
      path.join(DIMIAO_DIR,`page_${bookPage}-${String(bookPage).padStart(3,'0')}.png`),
      path.join(DIMIAO_DIR,`page_${bookPage}-${String(bookPage).padStart(2,'0')}.png`),
      path.join(DIMIAO_DIR,`page_${bookPage}-${bookPage}.png`),
    ];
    for(const f of candidates){if(fs.existsSync(f)) return f;}
    return null;
  }
  function getSlideImages(s){
    const allText=extractAllText(s);
    const imgs=[];
    const km=allText.match(/Knight\s*\d{4}\s*s\.(\d+)/);
    if(km){const img=findKnightGsImg(parseInt(km[1]));if(img) imgs.push({path:img,label:'Knight s.'+km[1]});}
    const dm=allText.match(/Di\s*Maio\s*\d{4}\s*s\.(\d+)/);
    if(dm){const img=findDiMaioImg(parseInt(dm[1]));if(img) imgs.push({path:img,label:'DiMaio s.'+dm[1]});}
    return imgs;
  }
  function extractAllText(obj){
    let texts=[];
    if(typeof obj==='string') texts.push(obj);
    else if(obj&&typeof obj==='object'){
      for(const v of Object.values(obj)){
        if(typeof v==='string') texts.push(v);
        else if(Array.isArray(v)) v.forEach(item=>{
          if(typeof item==='string') texts.push(item);
          else if(item&&typeof item==='object') Object.values(item).forEach(x=>{if(typeof x==='string') texts.push(x);});
        });
      }
    }
    return texts.join(' ');
  }

  const SW_IN=10, SH_IN=7.5;
  const MX_IN=0.38;
  const CT_IN=1.04;
  const CH_IN=5.9;
  const CW_IN=SW_IN-2*MX_IN;
  const COL_IN=4.48;
  const FOOT_Y=7.13;

  function addTitleBar(slide,text){
    slide.addShape(pptx.ShapeType.rect,{x:0,y:0,w:SW_IN,h:0.87,fill:{color:NAVY}});
    slide.addText(text,{x:0.38,y:0.12,w:SW_IN-0.7,h:0.63,fontSize:20,fontFace:'Calibri Light',bold:true,color:'FFFFFF',valign:'middle'});
    slide.addShape(pptx.ShapeType.rect,{x:0,y:0.87,w:SW_IN,h:0.05,fill:{color:ACCENT}});
  }

  function addFooter(slide,ref){
    const txt=INST+(ref?'  |  '+ref:'');
    slide.addText(txt,{x:MX_IN,y:FOOT_Y,w:CW_IN,h:0.28,fontSize:8,fontFace:'Calibri',italic:true,color:GRAY,valign:'middle'});
  }

  function linesToTextRows(lines){
    const rows=[];
    for(const l of lines){
      if(typeof l==='string'){
        rows.push({text:'\u2022  '+l,options:{fontSize:14,fontFace:'Calibri',color:NAVY,lineSpacing:18,paraSpaceAfter:2,bullet:false}});
      } else if(l.head){
        rows.push({text:l.head,options:{fontSize:15,fontFace:'Calibri Light',bold:true,color:DBLUE,lineSpacing:20,paraSpaceBefore:6,paraSpaceAfter:2,bullet:false}});
      } else if(l.sub){
        rows.push({text:'  \u2022  '+l.sub,options:{fontSize:13,fontFace:'Calibri',color:DGRAY,lineSpacing:17,paraSpaceAfter:1,bullet:false}});
      } else if(l.note){
        rows.push({text:l.note,options:{fontSize:11,fontFace:'Calibri',italic:true,color:GRAY,lineSpacing:15,paraSpaceBefore:3,paraSpaceAfter:1,bullet:false}});
      }
    }
    return rows;
  }

  function buildCover(s){
    const slide=pptx.addSlide();
    slide.addImage({path:coverImgPath,x:0,y:0,w:SW_IN,h:SH_IN});
    slide.addShape(pptx.ShapeType.rect,{x:0,y:0,w:SW_IN,h:SH_IN,fill:{color:NAVY,transparency:22}});
    slide.addText(s.title,{x:0.55,y:1.64,w:SW_IN-1.1,h:0.87,fontSize:32,fontFace:'Calibri Light',bold:true,color:'FFFFFF',align:'center',lineSpacing:38});
    slide.addText(s.subtitle,{x:0.55,y:2.74,w:SW_IN-1.1,h:0.44,fontSize:16,fontFace:'Calibri Light',color:'B0C4DE',align:'center',lineSpacing:24});
    slide.addText(s.author||'',{x:0.55,y:3.40,w:SW_IN-1.1,h:0.38,fontSize:14,fontFace:'Calibri',color:'87CEEB',align:'center'});
    slide.addText(INST+'  |  Ankara, 2026',{x:0.55,y:4.0,w:SW_IN-1.1,h:0.27,fontSize:10,fontFace:'Calibri',color:GRAY,align:'center'});
  }

  function buildDivider(s){
    const slide=pptx.addSlide();
    slide.background={fill:NAVY};
    slide.addText(s.section,{x:0.55,y:1.86,w:SW_IN-1.1,h:0.38,fontSize:13,fontFace:'Calibri Light',bold:true,color:'87CEEB'});
    slide.addText(s.title,{x:0.55,y:2.35,w:SW_IN-1.1,h:0.87,fontSize:28,fontFace:'Calibri Light',bold:true,color:'FFFFFF',lineSpacing:34});
    if(s.desc) slide.addText(s.desc,{x:0.55,y:3.40,w:SW_IN-1.1,h:0.44,fontSize:13,fontFace:'Calibri',italic:true,color:'B0C4DE'});
    addFooter(slide,'');
  }

  function buildContent(s){
    const slide=pptx.addSlide();
    slide.background={fill:BGBLUE};
    addTitleBar(slide,s.title);
    const col1=s.L||[];
    const col2=s.R||[];
    const hasTwo=col2.length>0;
    if(hasTwo){
      slide.addShape(pptx.ShapeType.rect,{x:MX_IN,y:CT_IN,w:COL_IN,h:CH_IN,fill:{color:LTBLUE}});
      slide.addText(linesToTextRows(col1),{x:MX_IN+0.1,y:CT_IN+0.05,w:COL_IN-0.2,h:CH_IN-0.1,valign:'top'});
      slide.addShape(pptx.ShapeType.rect,{x:MX_IN+COL_IN+0.22,y:CT_IN,w:COL_IN,h:CH_IN,fill:{color:'FFFFFF'}});
      slide.addText(linesToTextRows(col2),{x:MX_IN+COL_IN+0.32,y:CT_IN+0.05,w:COL_IN-0.2,h:CH_IN-0.1,valign:'top'});
    } else {
      slide.addShape(pptx.ShapeType.rect,{x:MX_IN,y:CT_IN,w:CW_IN,h:CH_IN,fill:{color:'FFFFFF'}});
      slide.addText(linesToTextRows(col1),{x:MX_IN+0.1,y:CT_IN+0.05,w:CW_IN-0.2,h:CH_IN-0.1,valign:'top'});
    }
    addFooter(slide,s.ref||'');
  }

  function buildTable(s){
    const slide=pptx.addSlide();
    slide.background={fill:BGBLUE};
    addTitleBar(slide,s.title);
    const headers=s.H||[];
    const rows=s.R||[];
    const tblRows=[];
    tblRows.push(headers.map(h=>({text:h,options:{fontSize:12,fontFace:'Calibri',bold:true,color:'FFFFFF',align:'center',fill:{color:NAVY}}})));
    rows.forEach((row,ri)=>{
      const bg=ri%2===0?LTBLUE:'FFFFFF';
      tblRows.push(row.map((cell,ci)=>({text:cell,options:{fontSize:11,fontFace:'Calibri',bold:ci===0,color:ci===0?NAVY:DGRAY,align:ci===0?'left':'center',fill:{color:bg},border:[null,null,{pt:0.5,color:ACCENT},null]}})));
    });
    slide.addTable(tblRows,{x:MX_IN,y:CT_IN,w:CW_IN,colW:Array(headers.length).fill(CW_IN/headers.length),rowH:0.4,border:{pt:0,color:'FFFFFF'},autoPage:false});
    addFooter(slide,s.ref||'');
  }

  function buildDiagram(s){
    const slide=pptx.addSlide();
    slide.background={fill:BGBLUE};
    addTitleBar(slide,s.title);
    const lines=s.D||[];
    const textRows=[];
    for(const l of lines){
      if(!l||l===''){
        textRows.push({text:' ',options:{fontSize:4,lineSpacing:6}});
      } else if(l.startsWith('##')){
        textRows.push({text:l.replace(/^##\s*/,''),options:{fontSize:16,fontFace:'Calibri Light',bold:true,color:NAVY,align:'center',lineSpacing:22,paraSpaceBefore:4,paraSpaceAfter:3}});
      } else if(l.startsWith('#')){
        textRows.push({text:l.replace(/^#\s*/,''),options:{fontSize:14,fontFace:'Calibri Light',bold:true,color:DBLUE,lineSpacing:19,paraSpaceBefore:5,paraSpaceAfter:2}});
      } else if(l.startsWith('>')){
        textRows.push({text:l.replace(/^>\s*/,''),options:{fontSize:11,fontFace:'Calibri',italic:true,color:GRAY,lineSpacing:15,paraSpaceBefore:2,paraSpaceAfter:1}});
      } else {
        textRows.push({text:l,options:{fontSize:12,fontFace:'Calibri',color:DGRAY,lineSpacing:16,paraSpaceAfter:2}});
      }
    }
    slide.addShape(pptx.ShapeType.rect,{x:MX_IN,y:CT_IN,w:CW_IN,h:CH_IN,fill:{color:'FFFFFF'}});
    slide.addText(textRows,{x:MX_IN+0.1,y:CT_IN+0.05,w:CW_IN-0.2,h:CH_IN-0.1,valign:'top'});
    addFooter(slide,s.ref||'');
  }

  // ─── GENERATE ALL SLIDES ───────────────────────────────────────────────────
  console.log(`Generating ${SLIDES.length} slides with pptxgenjs...`);
  let count=0;
  for(const s of SLIDES){
    count++;
    try{
      if(s.type==='cov') buildCover(s);
      else if(s.type==='div') buildDivider(s);
      else if(s.type==='c') buildContent(s);
      else if(s.type==='t') buildTable(s);
      else if(s.type==='d') buildDiagram(s);
      else buildContent({...s,title:s.title||'Slayt '+count,L:s.L||[],R:s.R||[]});
    }catch(e){
      console.warn(`Slide ${count} error: ${e.message}`);
      const slide=pptx.addSlide();
      slide.background={fill:BGBLUE};
      slide.addText('Slayt '+count,{x:0.5,y:0.5,w:9,h:1,fontSize:20,color:NAVY});
    }
  }

  // ─── SAVE ──────────────────────────────────────────────────────────────────
  const OUT='client/public/gazi_adli_tip_ASY.pptx';
  await pptx.writeFile({fileName:OUT});
  const sz=fs.statSync(OUT).size;
  console.log(`\n✓ Output: ${OUT}`);
  console.log(`✓ Slides: ${count}`);
  console.log(`✓ Size: ${(sz/1024/1024).toFixed(2)} MB`);
}
main().catch(e=>{console.error('FATAL:',e.message,'\n',e.stack);process.exit(1);});
